VIEW = {"ang": [0.3, 0.7, 1.1, 0.5, 0.9, 1.3], "yaw": 0.4, "pitch": 0.25}


@pytest.mark.parametrize("i", range(len(SHAPES)), ids=[s.name for s in SHAPES])
def test_shape_renders(ctx, i):
    s = ViewState(shape=i, ang=list(VIEW["ang"]), yaw=VIEW["yaw"], pitch=VIEW["pitch"])
