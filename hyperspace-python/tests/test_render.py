def _window(ctx, w=160, h=100):
    """A stand-in for the render window's default framebuffer."""
    win = ctx.framebuffer(color_attachments=[ctx.renderbuffer((w, h), 4)])
    win.use()
    ctx.viewport = (0, 0, w, h)
    return win


def _pixels(win):
    return np.frombuffer(win.read(components=3), dtype=np.uint8).astype(int)


def test_a_look_back_frame_with_no_worker_leaves_the_window_bound(ctx):
    """The owner's freeze, headless: WAKE's look-back (on, every 2) with no
    dream worker left the history atlas bound on the frames off the
    cadence, so every later frame drew into the atlas while the window
    showed one picture. Nothing rebinds the window between frames here —
    as in the app before its explicit `ctx.screen.use()`."""
    from hyperspace.render import Renderer

    win = _window(ctx)
    r = Renderer(ctx)
    st = r.lookback.state
    st.on, st.every, st.echoes, st.tint_from = True, 2, 16, 0
    r.lookback.source = None
    s = ViewState(shape=3, planes=[True] * 6)
    prev = None
    for k in range(3):
        s.ang = [a + 0.3 for a in s.ang]
        r.draw(s, 160, 100, t_now=float(k))
        assert ctx.fbo is win, f"frame {k} left framebuffer {ctx.fbo.glo} bound"
        assert ctx.viewport == (0, 0, 160, 100)
        px = _pixels(win)
        if prev is not None:
            assert np.abs(px - prev).mean() > 0.5, f"frame {k}: the window did not change"
        prev = px
    win.release()


def test_one_raising_frame_does_not_strand_the_next(ctx):
    """An exception inside draw after a `.use()` stranded that framebuffer
    for good; the target is bound again on the way out, so the next frame
    draws to the window."""
    from hyperspace.render import Renderer

    win = _window(ctx)
    r = Renderer(ctx)
    s = ViewState(shape=3, planes=[True] * 6)
    r.draw(s, 160, 100, t_now=0.0)
    before = _pixels(win)
    real = r.draw_scene

    def once(*a, **k):
        r.draw_scene = real
        raise RuntimeError("one bad frame")

    r.draw_scene = once
    s.ang = [a + 0.3 for a in s.ang]
    with pytest.raises(RuntimeError):
        r.draw(s, 160, 100, t_now=1.0)
    assert ctx.fbo is win
    s.ang = [a + 0.3 for a in s.ang]
    r.draw(s, 160, 100, t_now=2.0)
    assert ctx.fbo is win
    assert np.abs(_pixels(win) - before).mean() > 0.5, "the next frame must reach the window"
    win.release()


