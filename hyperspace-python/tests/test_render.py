def test_pixels_land_on_projection(ctx):
    """Bright pixels must appear at the projected vertex positions of the
    golden view — ties the raster output to the parity-proven transform."""
    ref = json.loads((GOLDEN / "geometry" / "03-tesseract.json").read_text())
    view = ref["views"][1]
    s = ViewState(shape=3, ang=list(view["ang"]), yaw=view["yaw"], pitch=view["pitch"])
    w, h = ref["viewport"]["width"], ref["viewport"]["height"]
    img = render_offscreen(s, w, h, ctx=ctx)
    g = geom(3)
    px, py, _ = project(g["V"], view["ang"], view["yaw"], view["pitch"], w=w, h=h)
    for x, y in zip(px, py):
        xi, yi = round(x), round(y)
        patch = img[max(yi - 3, 0) : yi + 4, max(xi - 3, 0) : xi + 4]
        assert patch.max() > 40, f"nothing rendered near projected vertex ({xi},{yi})"


def test_render_performance(ctx):
    """120-cell (1200 edges) and 20,20-duoprism (800 edges) at 1080p:
    raw draw must be comfortably above 60 fps equivalent."""
    import time

    from hyperspace.render import Renderer

    fbo = ctx.framebuffer(color_attachments=[ctx.renderbuffer((1920, 1080))])
    fbo.use()
    ctx.viewport = (0, 0, 1920, 1080)
    r = Renderer(ctx)
    for shape in (15, 14):
        s = ViewState(shape=shape, ang=list(VIEW["ang"]))
        r.draw(s, 1920, 1080)  # warm the caches
        t0 = time.perf_counter()
        n = 120
        for k in range(n):
            s.ang[3] += 0.01
            r.draw(s, 1920, 1080)
        ctx.finish()
        fps = n / (time.perf_counter() - t0)
        assert fps > 60, f"{SHAPES[shape].name}: {fps:.0f} fps"
    fbo.release()


