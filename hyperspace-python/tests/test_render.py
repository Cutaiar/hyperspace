def test_on_reload_rebuilds_the_wire_programs_and_still_draws(ctx):
    """Hot-swap hook: every GL program is recompiled, the buffers and the
    look-back / FX / cover objects persist, and the next frame draws. No
    hasattr backfills — a missing attribute is the reloader's error to
    report (audit H3)."""
    from hyperspace.render import Renderer

    w, h = 320, 200
    fbo = ctx.framebuffer(color_attachments=[ctx.renderbuffer((w, h))])
    r = Renderer(ctx)
    keep = (r.lookback, r.fx, r.cover, r._lbuf, r._pbuf, r._fbuf)
    old = (r._lines, r._points, r._cover_prog)
    r.on_reload()
    assert (r.lookback, r.fx, r.cover, r._lbuf, r._pbuf, r._fbuf) == keep
    assert all(a is not b for a, b in zip(old, (r._lines, r._points, r._cover_prog)))
    s = ViewState(shape=10, ang=list(VIEW["ang"]), faces=True, pattern=2)
    _direct(ctx, r, s, fbo, w, h, 0.3)
    assert ctx.error == "GL_NO_ERROR"
    assert _rgba(ctx, fbo, w, h, 0).max() > 0
    fbo.release()


def test_build_wire_programs_releases_what_it_made_when_a_step_raises():
    """A VAO build that fails after the programs compiled must not leak them
    (and the live set stays untouched) — headless, over a fake context."""
    from types import SimpleNamespace

    from hyperspace.render import Renderer

    released = []

    class Prog:
        def __init__(self):
            self.uniforms = {}

        def __getitem__(self, k):
            return self.uniforms.setdefault(k, SimpleNamespace())

        def release(self):
            released.append(self)

    def vertex_array(*_):
        raise RuntimeError("no VAO today")

    r = Renderer.__new__(Renderer)
    r.ctx = SimpleNamespace(program=lambda **_: Prog(), vertex_array=vertex_array)
    r._lbuf = r._pbuf = r._fbuf = object()
    r._lines = r._points = r._lvao = r._cover_prog = r._cvao = r._pvao = "live"
    with pytest.raises(RuntimeError):
        r._build_wire_programs()
    assert len(released) == 2                      # both compiled programs
    assert r._lines == "live" and r._lvao == "live"   # the old set was not replaced


# ---- plan 14 WP1: the freeze — every render frame ends on its target ----

def _window(ctx, w=160, h=100):
    """A stand-in for the render window's default framebuffer."""
    win = ctx.framebuffer(color_attachments=[ctx.renderbuffer((w, h), 4)])
    win.use()
    ctx.viewport = (0, 0, w, h)
    return win


def _pixels(win):
    return np.frombuffer(win.read(components=3), dtype=np.uint8).astype(int)


def test_a_look_back_frame_with_no_worker_leaves_the_window_bound(ctx):
    """The owner's freeze, headless: WAKE's look-back (on, every 2) with no
    dream worker left the history atlas bound on the frames off the
    cadence, so every later frame drew into the atlas while the window
    showed one picture. Nothing rebinds the window between frames here —
    as in the app before its explicit `ctx.screen.use()`."""
    from hyperspace.render import Renderer

    win = _window(ctx)
    r = Renderer(ctx)
    st = r.lookback.state
    st.on, st.every, st.echoes, st.tint_from = True, 2, 16, 0
    r.lookback.source = None
    s = ViewState(shape=3, planes=[True] * 6)
    prev = None
    for k in range(3):
        s.ang = [a + 0.3 for a in s.ang]
        r.draw(s, 160, 100, t_now=float(k))
        assert ctx.fbo is win, f"frame {k} left framebuffer {ctx.fbo.glo} bound"
        assert ctx.viewport == (0, 0, 160, 100)
        px = _pixels(win)
        if prev is not None:
            assert np.abs(px - prev).mean() > 0.5, f"frame {k}: the window did not change"
        prev = px
    win.release()


def test_one_raising_frame_does_not_strand_the_next(ctx):
    """An exception inside draw after a `.use()` stranded that framebuffer
    for good; the target is bound again on the way out, so the next frame
    draws to the window."""
    from hyperspace.render import Renderer

    win = _window(ctx)
    r = Renderer(ctx)
    s = ViewState(shape=3, planes=[True] * 6)
    r.draw(s, 160, 100, t_now=0.0)
    before = _pixels(win)
    real = r.draw_scene

    def once(*a, **k):
        r.draw_scene = real
        raise RuntimeError("one bad frame")

    r.draw_scene = once
    s.ang = [a + 0.3 for a in s.ang]
    with pytest.raises(RuntimeError):
        r.draw(s, 160, 100, t_now=1.0)
    assert ctx.fbo is win
    s.ang = [a + 0.3 for a in s.ang]
    r.draw(s, 160, 100, t_now=2.0)
    assert ctx.fbo is win
    assert np.abs(_pixels(win) - before).mean() > 0.5, "the next frame must reach the window"
    win.release()


# ---- plan 15 WP3: the master dim — the frame's last pass, a multiply ----

DW, DH = 480, 320


def _hands():
    """Two synthetic hands, as tests/test_ghost.py feeds the ghost."""
    from test_ghost import tracker

    return tracker()


def _dim_renderer(ctx, *, effect=True, hands=True, bg_alpha=1.0, echoes=False):
    """A renderer with an effect on and the ghost hands over it."""
    from hyperspace.fx import FxState
    from hyperspace.render import Renderer

    fx = FxState()
    fx.values["warp"]["on"] = effect
    r = Renderer(ctx, fx=fx)
    r.bg_alpha = bg_alpha
    r.ghost.state.on, r.ghost.state.alpha = hands, 1.0
    r.ghost.source = _hands() if hands else None
    if echoes:
        st = r.lookback.state
        st.on, st.echoes, st.gap, st.tint_from = True, 8, 0.0, 0
        r.lookback.source = None
    return r


def _dim_frames(ctx, r, dim, frames=4, t0=2.0, spin=0.0):
    """RGBA (as ints) after `frames` frames at 30 fps with the master at
    `dim` (None: left as the renderer has it)."""
    fbo = ctx.framebuffer(color_attachments=[ctx.renderbuffer((DW, DH), 4)])
    if dim is not None:
        r.dim = dim
    s = ViewState(shape=10, ang=list(VIEW["ang"]), yaw=VIEW["yaw"], pitch=VIEW["pitch"],
                  faces=True, pattern=2)
    for k in range(frames):
        s.ang = [a + spin for a in s.ang]
        fbo.use()
        ctx.viewport = (0, 0, DW, DH)
        r.draw(s, DW, DH, t_now=t0 + k / 30)
        assert ctx.fbo is fbo and ctx.viewport == (0, 0, DW, DH)   # ends on its target
    out = np.frombuffer(fbo.read(components=4), dtype=np.uint8).reshape(DH, DW, 4)[::-1]
    fbo.release()
    assert ctx.error == "GL_NO_ERROR"
    return out.astype(int)


def test_dim_at_one_is_the_old_frame_exactly(ctx, monkeypatch):
    """At 1 the pass does not run — no program is built, `dim_pass` is never
    called — and the frame, effect and ghost hands on, is bit-identical to
    one from a renderer that has no `dim` at all (one made before a hot
    reload brought the attribute)."""
    from hyperspace.render import Renderer

    old = _dim_renderer(ctx)
    del old.dim, old.dim_error, old._dim_prog, old._dim_vao
    want = _dim_frames(ctx, old, None)
    assert not hasattr(old, "dim")
    calls = []
    real = Renderer.dim_pass
    monkeypatch.setattr(Renderer, "dim_pass",
                        lambda self, *a, **k: calls.append(a) or real(self, *a, **k))
    r = _dim_renderer(ctx)
    got = _dim_frames(ctx, r, 1.0)
    assert want[..., :3].max() > 100 and r.fx.active()
    assert np.array_equal(got, want)
    assert calls == [] and r._dim_prog is None and r.dim_error == ""
    # and the pass leaves the GL state as it found it: after dimmed frames,
    # full again is what the renderer that never dimmed draws next
    later = _dim_frames(ctx, old, None, t0=3.0)
    again = _dim_frames(ctx, old, None, t0=4.0)
    assert not np.array_equal(_dim_frames(ctx, r, 0.3, t0=3.0), later)
    assert len(calls) == 4 and r._dim_prog is not None
    assert np.array_equal(_dim_frames(ctx, r, 1.0, t0=4.0), again)
    assert len(calls) == 4
    old.on_reload()                                # a reload of the old renderer: no raise
    assert old.dim_error == "" and old._dim_prog is None


