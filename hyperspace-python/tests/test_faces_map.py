"""Plan 37 C4 (the dry run of P2): the face patterns' migration map,
docs/plans/assets/37-faces/migration-map.md, is generated by
tools/faces_sheets.py from the presets as the real loader lands them —
this holds the file to them, so it cannot rot silently — and its
`dropped → nearest kept` rule answers for any subset the owner keeps."""

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "tools") not in sys.path:
    sys.path.insert(0, str(ROOT / "tools"))

import faces_sheets as fs

from hyperspace.patterns import NAMES


# in the fast tier on purpose (~1.5 s, one load per preset): a preset edit
# that leaves the map stale fails on the next bare `pytest`
def test_the_map_matches_every_preset_and_fixture_as_loaded():
    """Every corpus preset's and fixture's mode, faces switch and faces
    wire in the map are what the files load to (`--check`)."""
    assert fs.check() == []


@pytest.mark.slow
def test_the_usage_reads_the_drawn_faces_wire():
    uses = {u.slug: u for u in fs.usage()}
    assert set(uses) >= {p.stem for p in fs.CORPUS.glob("*.json")}
    assert uses["party-faces"].state == "on screen" and uses["party-faces"].name == "HEX"
    assert uses["party-faces"].path == ("pattern", "shape.faces")
    assert uses["legacy6"].state == "faces off"           # wired, view.faces off
    assert uses["delay-faces"].state == "unwired"         # the faces read a delay


def test_every_mode_has_a_line_and_a_ranked_list_of_other_modes():
    assert list(fs.DRAWS) == NAMES and list(fs.NEAREST) == NAMES
    for n in NAMES:
        near = [x for x, why in fs.NEAREST[n]]
        assert len(near) >= 2 and n not in near and set(near) <= set(NAMES), n
        assert len(set(near)) == len(near), n
        assert all(why for _, why in fs.NEAREST[n]), n


def test_nearest_kept_answers_for_any_subset():
    assert fs.nearest_kept("HEX", ["HEX", "RINGS"]) == "HEX"          # kept stays
    assert fs.nearest_kept("HEX", ["CELLS", "PLASMA"]) == "CELLS"     # first in its list
    assert fs.nearest_kept("HEX", ["TRUCHET", "CELLS"]) == "CELLS"    # rank, not order given
    assert fs.nearest_kept("HEX", ["PLASMA"]) == "PLASMA"             # none listed: first kept
    assert fs.nearest_kept("HEX", ["FLAT", "PLASMA"]) == "PLASMA"     # FLAT only as last resort
    assert fs.nearest_kept("HEX", ["FLAT"]) == "FLAT"
    for n in NAMES:
        for keep in (["PLASMA"], ["RINGS", "EMBER"], NAMES[5:9]):
            assert fs.nearest_kept(n, keep) in keep
    with pytest.raises(ValueError):
        fs.nearest_kept("HEX", [])
