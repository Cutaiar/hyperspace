"""Plan-02 checks: every shape renders offscreen without GL errors, and the
rendered pixels land where the proven projection says they should.

Screenshot side-by-sides against the HTML (the actual exit judge, by eye)
are generated by tools/compare_render.py into docs/plans/assets/.
"""

import json
from pathlib import Path

import pytest

moderngl = pytest.importorskip("moderngl")

from hyperspace.geometry import SHAPES, geom, project
from hyperspace.render import ViewState, render_offscreen

GOLDEN = Path(__file__).parent / "golden"


@pytest.fixture(scope="module")
def ctx():
    try:
        c = moderngl.create_context(standalone=True)
    except Exception as e:  # noqa: BLE001 — any GL failure means skip
        pytest.skip(f"no standalone GL context available: {e}")
    yield c
    c.release()


VIEW = {"ang": [0.3, 0.7, 1.1, 0.5, 0.9, 1.3], "yaw": 0.4, "pitch": 0.25}


@pytest.mark.parametrize("i", range(len(SHAPES)), ids=[s.name for s in SHAPES])
def test_shape_renders(ctx, i):
    s = ViewState(shape=i, ang=list(VIEW["ang"]), yaw=VIEW["yaw"], pitch=VIEW["pitch"])
    img = render_offscreen(s, 600, 400, ctx=ctx)
    assert ctx.error == "GL_NO_ERROR"
    assert img.shape == (400, 600, 3)
    assert img.max() > 0, "frame is entirely black"
    # red vertex pixels and white-ish edge pixels both present
    assert (img[:, :, 0] > img[:, :, 1]).any(), "no red-dominant (vertex) pixels"


def test_pixels_land_on_projection(ctx):
    """Bright pixels must appear at the projected vertex positions of the
    golden view — ties the raster output to the parity-proven transform."""
    ref = json.loads((GOLDEN / "geometry" / "03-tesseract.json").read_text())
    view = ref["views"][1]
    s = ViewState(shape=3, ang=list(view["ang"]), yaw=view["yaw"], pitch=view["pitch"])
    w, h = ref["viewport"]["width"], ref["viewport"]["height"]
    img = render_offscreen(s, w, h, ctx=ctx)
    g = geom(3)
    px, py, _ = project(g["V"], view["ang"], view["yaw"], view["pitch"], w=w, h=h)
    for x, y in zip(px, py):
        xi, yi = round(x), round(y)
        patch = img[max(yi - 3, 0) : yi + 4, max(xi - 3, 0) : xi + 4]
        assert patch.max() > 40, f"nothing rendered near projected vertex ({xi},{yi})"


def test_render_performance(ctx):
    """120-cell (1200 edges) and 20,20-duoprism (800 edges) at 1080p:
    raw draw must be comfortably above 60 fps equivalent."""
    import time

    from hyperspace.render import Renderer

    fbo = ctx.framebuffer(color_attachments=[ctx.renderbuffer((1920, 1080))])
    fbo.use()
    ctx.viewport = (0, 0, 1920, 1080)
    r = Renderer(ctx)
    for shape in (15, 14):
        s = ViewState(shape=shape, ang=list(VIEW["ang"]))
        r.draw(s, 1920, 1080)  # warm the caches
        t0 = time.perf_counter()
        n = 120
        for k in range(n):
            s.ang[3] += 0.01
            r.draw(s, 1920, 1080)
        ctx.finish()
        fps = n / (time.perf_counter() - t0)
        assert fps > 60, f"{SHAPES[shape].name}: {fps:.0f} fps"
    fbo.release()


def test_faces_render(ctx):
    s = ViewState(shape=3, ang=list(VIEW["ang"]), faces=True)
    img = render_offscreen(s, 600, 400, ctx=ctx)
    assert ctx.error == "GL_NO_ERROR"
    base = render_offscreen(ViewState(shape=3, ang=list(VIEW["ang"])), 600, 400, ctx=ctx)
    # translucent fills must add lit pixels beyond the wireframe
    assert (img > 8).sum() > (base > 8).sum()


def test_instances_grid(ctx):
    s = ViewState(shape=0, ang=list(VIEW["ang"]), instances=9, zoom=0.25)
    img = render_offscreen(s, 800, 600, ctx=ctx)
    assert ctx.error == "GL_NO_ERROR"
    assert img.max() > 0
    # nine copies spread wider than one: lit pixels in all four quadrants
    for ys, xs in ((slice(0, 300), slice(0, 400)), (slice(0, 300), slice(400, 800)),
                   (slice(300, 600), slice(0, 400)), (slice(300, 600), slice(400, 800))):
        assert img[ys, xs].max() > 0, "instance grid missing from a quadrant"


def test_zoom_and_pan(ctx):
    base = render_offscreen(ViewState(shape=3, ang=list(VIEW["ang"])), 600, 400, ctx=ctx)
    panned = render_offscreen(
        ViewState(shape=3, ang=list(VIEW["ang"]), pan=[150.0, 0.0]), 600, 400, ctx=ctx
    )
    import numpy as np
    # panning right moves the lit centroid right by ~the pan distance
    ys, xs = np.nonzero(base.max(axis=2) > 8)
    ys2, xs2 = np.nonzero(panned.max(axis=2) > 8)
    assert abs((xs2.mean() - xs.mean()) - 150) < 4
    assert abs(ys2.mean() - ys.mean()) < 4
